it('covers every documented API method with a dedicated resource method', function (): void {
    $client = baseLinkerClient();
    $resources = ['orders', 'pickPack', 'invoices', 'receipts', 'returns', 'couriers', 'crm', 'inventory', 'warehouses', 'documents',
        'purchaseOrders', 'transfers', 'stocktakes', 'fulfillment', 'connect', 'externalStorages', 'listingAgents'];
    $available = [];

    foreach ($resources as $resource) {
        foreach ((new ReflectionClass($client->{$resource}()))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            $available[$method->getName()] = true;
        }
    }

    $missing = array_values(array_filter(DOCUMENTED_API_METHODS, static fn(string $name): bool => ! isset($available[$name])));

    expect(DOCUMENTED_API_METHODS)->toHaveCount(211)->and($missing)->toBe([]);
});

it('exposes every resource on the client', function (): void {
    expect((new ReflectionClass(BaseLinkerClient::class))->getMethods(ReflectionMethod::IS_PUBLIC))->toHaveCount(21);
});
